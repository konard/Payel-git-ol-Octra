// Package search реализует слой веб-поиска для ресёрч-задач Octra.
//
// Архитектура повторяет иерархию системы: босс расширяет задачу и создаёт
// менеджеров поиска, менеджеры задают диапазон поиска (ссылки, теги, новости,
// информация), а воркеры выполняют сам поиск этим пакетом. Воркер получает
// сырые результаты от Provider (по умолчанию — DuckDuckGo), переранжирует их
// базовым алгоритмом BM25 (как на схеме из issue) и передаёт лучшие источники
// в LLM для финального ответа.
//
// Пакет спроектирован так, чтобы не требовать сети в тестах: Provider — это
// интерфейс, а ранжирование BM25 и форматирование полностью детерминированы.
package search

import (
	"context"
	"strings"
)

// Result — одна найденная веб-страница.
type Result struct {
	Title   string  // заголовок страницы
	URL     string  // полный URL
	Snippet string  // краткое описание / выдержка
	Source  string  // домен (например, "habr.com")
	Score   float64 // релевантность после ранжирования (BM25)
}

// Provider — источник результатов поиска (поисковая система).
// Реализуется DuckDuckGoProvider, а в тестах — заглушкой.
type Provider interface {
	// Search возвращает до limit результатов по запросу query.
	Search(ctx context.Context, query string, limit int) ([]Result, error)
}

// text возвращает текст для ранжирования: заголовок + сниппет.
func (r Result) text() string {
	return strings.TrimSpace(r.Title + " " + r.Snippet)
}

